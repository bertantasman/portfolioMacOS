// Writes docs/DEVELOPER_STATISTICS.md from the live GitHub inventory and the committed analysis records:
// `npm run stats-report`. Needs the GitHub account configured (siteConfig or GITHUB_USERNAME).
import { writeFileSync } from "node:fs";
import path from "node:path";
import { projectAnalysis } from "@/data/project-content/analysis";
import { getConfiguredUsername } from "@/lib/github/config";
import { getRepositories } from "@/lib/github/repositories";
import { computeStatistics, STAT_CATEGORIES } from "@/lib/projects/statistics";
import { deriveRegistry } from "@/lib/projects/registry";

const configured = getConfiguredUsername();
if (configured.username === null) {
  console.error("No GitHub account is configured.");
  process.exit(1);
}
const result = await getRepositories();
if (!result.ok) {
  console.error(`GitHub: ${result.message}`);
  process.exit(1);
}
const complete = !result.truncated && !result.stale;
const registry = deriveRegistry(result.repositories);
const s = computeStatistics(result.repositories, registry);
const analysis = new Map(projectAnalysis.map((a) => [a.projectId, a]));
const nameOf = (projectId: string) => s.byProject.get(projectId)?.repositoryName ?? projectId;
const list = (xs: readonly string[]) => (xs.length ? xs.join(", ") : "–");
const L: string[] = [];
const add = (...x: string[]) => L.push(...x);

add("# Developer statistics", "");
add("Generated by `npm run stats-report` from the account's public GitHub repositories and `src/data/project-content/analysis.ts`. The numbers shown in the GitHub app, Safari's Projects page and the About page come from the same code (`src/lib/projects/statistics.ts`).", "");
add(`- **Account:** \`${configured.username}\``);
add(`- **Generated:** ${new Date(result.fetchedAt).toISOString().slice(0, 10)} (${complete ? "complete GitHub snapshot" : "INCOMPLETE snapshot: truncated or stale"})`);
add("");
add("## Coverage", "");
add(`| | Count |`, `| --- | --- |`);
add(`| Public repositories in scope | ${s.scope.repositoriesInScope} |`);
add(`| Repositories with an analysis record | ${s.scope.analyzed} |`);
add(`| Counted as projects | ${s.scope.counted} |`);
add(`| Pending classification (no analysis record) | ${s.scope.pending.length}${s.scope.pending.length ? ` — ${list(s.scope.pending.map((p) => p.name))}` : ""} |`);
add(`| Excluded | ${s.scope.excluded.length} |`);
add("");
add(s.scope.pending.length === 0 ? "Every repository in scope has been analyzed." : "Repositories pending classification are not counted and receive no guessed categories.", "");

add("## Statistics", "");
add("| Statistic | Projects |", "| --- | --- |");
add(`| Total projects | ${s.totalProjects} |`);
for (const c of STAT_CATEGORIES) add(`| ${c.label} | ${s.categoryCounts[c.id]} |`);
add("", "Categories overlap: a project can be in several, so they do not add up to the total. Categories with 0 are hidden in the app.", "");

add("## Technologies named in project descriptions", "");
add("| Technology | Projects |", "| --- | --- |");
for (const t of s.technologies) add(`| ${t.name} | ${t.count} |`);
add("");

add("## Projects in each category", "");
for (const c of STAT_CATEGORIES) {
  const ids = s.projectsByCategory[c.id];
  add(`- **${c.label}** (${ids.length}): ${list(ids.map(nameOf))}`);
}
add("");

add("## Repository-by-repository classification", "");
add("| Repository | Counted | Platform | Frameworks | Fields | Confidence |", "| --- | --- | --- | --- | --- | --- |");
for (const repo of [...result.repositories].sort((a, b) => a.name.localeCompare(b.name, undefined, { sensitivity: "base" }))) {
  const a = analysis.get(`github:${repo.id}`);
  const ex = s.scope.excluded.find((e) => e.repositoryId === repo.id);
  const pend = s.scope.pending.some((p) => p.repositoryId === repo.id);
  const counted = ex ? `no: ${ex.reason.toLowerCase()}` : pend ? "pending" : "yes";
  add(`| ${repo.name} | ${counted} | ${list(a?.platforms ?? [])} | ${list(a?.frameworks ?? [])} | ${list(a?.areas ?? [])} | ${a ? a.classificationConfidence : "–"} |`);
}
add("");

add("## Evidence behind each classification", "");
for (const a of projectAnalysis.filter((x) => Object.keys(x.classificationEvidence).length > 0)) {
  add(`### ${a.repositoryName}`, "");
  for (const [k, v] of Object.entries(a.classificationEvidence)) add(`- **${k}:** ${v}`);
  add("");
}

add("## Uncertain classifications and items to review", "");
if (s.scope.needsReview.length === 0) add("None.");
for (const r of s.scope.needsReview) {
  const a = analysis.get(`github:${r.repositoryId}`)!;
  add(`- **${r.name}** (confidence ${a.classificationConfidence}):`);
  for (const n of a.classificationNotes) add(`  - ${n}`);
}
add("");

add("## Excluded repositories", "");
for (const e of s.scope.excluded) add(`- **${e.name}**: ${e.reason}`);
if (s.scope.excluded.length === 0) add("None.");
add("");

add("## Counting rules", "");
add(
  "1. **Scope.** The account's public GitHub repositories, fetched through the portfolio's own GitHub service (all pages). Private repositories and local-only projects are not included in this stage.",
  "2. **One count per repository.** Projects are identified by GitHub's numeric repository id, so a renamed repository is still one project and a repository can never be counted twice. A curated project linked to a repository is the same project, not an additional one.",
  "3. **What counts as a project.** A repository with an analysis record that is not a fork, not empty and not a non-project (such as the profile README repository).",
  "4. **Forks.** A fork is another developer's work. It is listed as excluded, and its platforms and frameworks are never attributed to the account.",
  "5. **Overlapping categories.** Each project counts once in every category it belongs to. A UIKit-based iOS app is in iOS and in UIKit, so category totals can exceed the project total.",
  "6. **Evidence first.** Platforms and frameworks are derived by `classifyFromSignals` from facts found in the repository (an Xcode project, imports, manifests, dependencies). A language alone never decides: Swift does not imply SwiftUI, Kotlin does not imply Android, Dart does not imply Flutter, and JavaScript or a package.json does not imply React or a web app. A UI framework must be imported in at least two files to count.",
  "7. **Technologies.** Counted from the technology lists in the written project descriptions (each name once per project; Firebase's services count as one technology). GitHub's primary language and topics are not used.",
  "8. **Uncertainty.** Where evidence is incomplete the classification carries a note and a lower confidence, and is listed above for review. Nothing is guessed to fill a category.",
  "9. **New repositories.** A repository without an analysis record is pending: shown as awaiting classification, never counted, and given no categories until it has been analysed.",
  "10. **Updating.** The statistics are recalculated whenever the repository list changes (a refresh, a rename, a new or removed repository).",
);
writeFileSync(path.resolve(process.cwd(), "docs/DEVELOPER_STATISTICS.md"), L.join("\n") + "\n");
console.log(`Wrote docs/DEVELOPER_STATISTICS.md (${s.scope.repositoriesInScope} repositories, ${s.totalProjects} counted)`);
